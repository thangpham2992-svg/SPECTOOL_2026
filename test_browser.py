 page.locator('#check').click();page.wait_for_timeout(400)
 print('MRL errors',page.locator('.check-error-row').all_text_contents()[:10],'top',page.locator('#check-top').inner_text())
 print('JS ERROR',errors[:20])
 browser.close()
